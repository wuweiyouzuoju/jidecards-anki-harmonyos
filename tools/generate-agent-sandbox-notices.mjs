// Generate notices from locked crate sources and immutable upstream revisions; checks are offline.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const native = join(root, 'native/agent-sandbox');
const asset = join(root, 'entry/src/main/resources/rawfile/agent-sandbox-notices.txt');
const manifest = join(native, 'engine/notices.json');
const hash = value => createHash('sha256').update(value).digest('hex');
const fingerprint = () => ({ lock: hash(readFileSync(join(native, 'Cargo.lock'))),
  engine: hash(readFileSync(join(native, 'engine/quickjs.wasm'))) });
const mode = process.argv[2] ?? '--check';
if (!['--write', '--check'].includes(mode) || process.argv.length > 3) throw Error('Usage: node tools/generate-agent-sandbox-notices.mjs [--check|--write]');
if (mode === '--check') {
  const saved = JSON.parse(readFileSync(manifest, 'utf8'));
  const current = fingerprint();
  if (saved.lock !== current.lock || saved.engine !== current.engine || saved.notices !== hash(readFileSync(asset))) {
    throw Error('Sandbox notices do not match lockfile/engine. Regenerate and review before shipping.');
  }
  console.log('[sandbox-notices] locked notices verified');
} else {
  const metadata = JSON.parse(execFileSync('cargo', ['metadata', '--locked', '--format-version', '1',
    '--manifest-path', join(native, 'Cargo.toml')], { cwd: root, encoding: 'utf8' }));
  const sections = ['jideCards Agent sandbox third-party notices\nGenerated by tools/generate-agent-sandbox-notices.mjs.\nIncludes all locked crates, including build-only and optional dependencies.\n'];
  const sources = [];
  const append = (title, text) => sections.push(`\n===== ${title} =====\n\n${text.replaceAll('\r\n', '\n').trim()}\n`);
  async function upstream(repository, revision, path, commentOnly = false) {
    const url = `https://raw.githubusercontent.com/${repository}/${revision}/${path}`;
    let text = execFileSync('curl', ['--fail', '--location', '--silent', '--show-error',
      '--retry', '2', '--max-time', '30', url], { encoding: 'utf8', maxBuffer: 2000000 });
    if (commentOnly) {
      const start = text.indexOf('/*'), end = text.indexOf('*/', start);
      if (start < 0 || end < 0) throw Error('Expected leading license comment: ' + url);
      text = text.slice(start, end + 2);
    }
    sources.push({ url, sha256: hash(text) });
    append(`${repository} @ ${revision} / ${path}`, text);
  }
  append('QuickJS-NG v0.17.0 / MIT', readFileSync(join(native, 'QUICKJS-LICENSE.txt'), 'utf8'));
  for (const pkg of metadata.packages.filter(p => p.source).sort((a,b) => `${a.name}-${a.version}`.localeCompare(`${b.name}-${b.version}`, 'en'))) {
    const dir = dirname(pkg.manifest_path);
    const files = readdirSync(dir).filter(f => /^(LICENSE|COPYRIGHT|COPYING|NOTICE)/i.test(f) && statSync(join(dir,f)).isFile());
    append(`${pkg.name} ${pkg.version}`, `License: ${pkg.license}\nSource: ${pkg.repository ?? pkg.source}`);
    if (files.length) for (const file of files.sort()) append(file, readFileSync(join(dir,file),'utf8'));
    else {
      const revision = JSON.parse(readFileSync(join(dir,'.cargo_vcs_info.json'),'utf8')).git.sha1;
      const repository = pkg.name.startsWith('wasmi') ? 'wasmi-labs/wasmi' : pkg.name === 'wasmparser' ? 'bytecodealliance/wasm-tools' : null;
      if (!repository) throw Error('Missing license files: ' + pkg.name);
      await upstream(repository, revision, 'LICENSE-MIT');
      await upstream(repository, revision, 'LICENSE-APACHE');
    }
  }
  const wasi = '1dfe5c302d1c5ab621f7abf04620fae92700fd22';
  for (const file of ['LICENSE','LICENSE-MIT','LICENSE-APACHE','LICENSE-APACHE-LLVM',
    'libc-top-half/musl/COPYRIGHT','libc-bottom-half/cloudlibc/LICENSE']) {
    await upstream('WebAssembly/wasi-libc',wasi,file);
  }
  await upstream('WebAssembly/wasi-libc',wasi,'dlmalloc/src/malloc.c',true);
  await upstream('WebAssembly/wasi-libc',wasi,'emmalloc/emmalloc.c',true);
  await upstream('llvm/llvm-project','08d094a0e457360ad8b94b017d2dc277e697ca76','compiler-rt/LICENSE.TXT');
  const text = sections.join('');
  writeFileSync(asset,text);
  writeFileSync(manifest,JSON.stringify({...fingerprint(),notices:hash(text),sources},null,2)+'\n');
  console.log(`[sandbox-notices] generated ${Buffer.byteLength(text)} bytes`);
}
