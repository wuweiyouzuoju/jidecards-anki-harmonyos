export const className = n => n.replace(/^anki\./, '').split(/[._]/).map(p => p[0].toUpperCase() + p.slice(1)).join('');
const cap = s => s[0].toUpperCase() + s.slice(1);
export function renderMessages(schema) {
  const out = ['// SPDX-License-Identifier: AGPL-3.0-or-later', '// Generated by tools/core-protocol.mjs; do not edit.',
    "import { WireMessage } from '../core/WireMessage';", "import { 协议写入器 } from '../core/ProtoWriter';", ''];
  for (const e of schema.enums) {
    const name=className(e.name);
    out.push(`export enum ${name} {`, ...e.values.map(v => `  ${v.name} = ${v.number},`), '}',
      `export type ${name}Value = ${[...new Set(e.values.map(v=>v.number))].join(' | ')};`,
      `export function isKnown${name}(value: number): boolean { return [${e.values.map(v=>name+'.'+v.name).join(', ')}].includes(value); }`, '');
  }
  for (const m of schema.messages) {
    out.push(`/** ${m.name}; 嵌套消息保持 raw；set 显式写入默认值，领域决定是否省略。 */`,
      `export class ${className(m.name)} extends WireMessage {`);
    for (const f of m.fields) {
      const name = cap(f.jsonName), raw = f.kind === 'message' || f.kind === 'bytes';
      const type = raw ? 'Uint8Array' : f.kind === 'string' ? 'string' : f.kind === 'bool' ? 'boolean' : 'number';
      const list = f.list || f.map;
      const oneof = f.oneof ? m.fields.filter(x => x.oneof === f.oneof).map(x => x.id) : null;
      const call = raw ? list ? `this.byteList(${f.id})` : f.kind === 'message' ? `this.messageBytes(${f.id}, [${oneof ?? []}])` : `this.bytes(${f.id}) ?? new Uint8Array(0)` :
        f.kind === 'string' ? `this.${list ? 'textList' : 'text'}(${f.id})` :
        f.kind === 'bool' && !list ? `this.booleanValue(${f.id})` :
        f.kind === 'bool' && list ? `this.bigList(${f.id}, 'uint64').map((v: bigint): boolean => v !== 0n)` : `this.${list ? 'numberList' : 'numberValue'}(${f.id}, '${f.kind}')`;
      out.push(`  static readonly FIELD_${f.jsonName}: number = ${f.id};`,
        `  has${name}Wire(): boolean { return this.hasWire(${f.id}, ${raw || f.kind === 'string' ? 2 : ['float','fixed32','sfixed32'].includes(f.kind) ? 5 : ['double','fixed64','sfixed64'].includes(f.kind) ? 1 : 0}); }`,
        `  has${name}(): boolean { return ${oneof ? `this.lastOneof([${oneof}]) === ${f.id}` : `this.has(${f.id})`}; }`,
        `  raw${name}(): Uint8Array[] { return this.rawFor(${f.id}); }`,
        `  count${name}(): number { return this.count(${f.id}); }`,
        `  get${name}(): ${type}${list ? '[]' : f.kind === 'message' ? ' | null' : ''} { ${oneof ? `if (!this.has${name}()) return ${f.kind === 'message' ? 'null' : f.kind === 'bytes' ? 'new Uint8Array(0)' : f.kind === 'string' ? "''" : f.kind === 'bool' ? 'false' : '0'}; ` : ''}return ${call}; }`);
      if (f.kind === 'message' && !list) out.push(`  get${name}Last(): Uint8Array | null { return this.bytes(${f.id}); }`);
      if (['int64','uint64','sint64','fixed64','sfixed64'].includes(f.kind)) out.push(
        `  get${name}Big(): bigint${list ? '[]' : ''} { ${oneof ? `if (!this.has${name}()) return 0n; ` : ''}return this.${list ? 'bigList' : 'bigValue'}(${f.id}, '${f.kind}'); }`,
        `  set${name}Big(value: bigint${list ? '[]' : ''}${list ? `, packed: boolean = ${f.packed}` : ''}): void { ${oneof ? `this.clearOneof([${oneof}]); ` : ''}this.appendBig(${f.id}, '${f.kind}', ${list ? 'value, packed' : '[value], false'}); }`);
      const setter = raw ? `this.append(${f.id}, value)` : f.kind === 'string' ? `this.appendText(${f.id}, value)` :
        `this.appendNumber(${f.id}, '${f.kind}', ${f.kind === 'bool' ? 'value ? 1 : 0' : 'value'})`;
      out.push(`  set${name}(value: ${type}${list ? '[]' : ''}${list && !raw && f.kind !== 'string' ? `, packed: boolean = ${f.packed}` : ''}): void {`,
        ...(oneof ? [`    this.clearOneof([${oneof}]);`] : []),
        list ? !raw && f.kind !== 'string' ? `    this.appendNumbers(${f.id}, '${f.kind}', value${f.kind === 'bool' ? '.map((v: boolean): number => v ? 1 : 0)' : ''}, packed);` :
          `    for (const item of value) ${setter.replace(/\bvalue\b/g, 'item')};` : `    ${setter};`, '  }');
      if (f.kind === 'message') out.push(`  set${name}Writer(value: 协议写入器${list ? '[]' : ''}): void { this.set${name}(${list ? 'value.map((item: 协议写入器): Uint8Array => item.转为字节())' : 'value.转为字节()'}); }`);
      if (f.kind === 'message' && !list) out.push(`  replace${name}(value: Uint8Array | null): void { const update = new ${className(m.name)}(); if (value !== null) update.set${name}(value); this.replace(${f.id}, update.toBytes()); }`);
    }
    out.push(`  preserved(): Uint8Array[] { return this.unknown([${m.fields.map(f => f.id)}]); }`, '}', '');
  }
  return out.join('\n');
}
export function dispatchBaseline(schema) {
  return { revision: schema.revision, fingerprint: schema.fingerprint, services: Object.fromEntries(schema.services
    .filter(s => s.name !== 'BackendFrontendService').map(s => [s.name.replace(/^Backend/, '').replace(/Service$/, '').replace(/([a-z])([A-Z])/g, '$1_$2').toLowerCase(),
      { id: s.id, methods: Object.fromEntries(s.methods.map(m => [m.id, m.name])) }])) };
}
export function renderClient(schema) {
  const out = ['// SPDX-License-Identifier: AGPL-3.0-or-later', '// Generated by tools/core-protocol.mjs; do not edit.',
    '/** 仅供领域 Service 使用；生成覆盖不表示产品接入或 JIDE 授权。 */',
    'export interface CoreTransport { 调用(service: number, method: number, input: Uint8Array): Promise<Uint8Array>; }',
    'export class CoreRpc {', '  private transport: CoreTransport;',
    '  constructor(transport: CoreTransport) { this.transport = transport; }'];
  for (const s of schema.services) for (const m of s.methods) out.push(
    `  ${s.name.replace(/^Backend/, '').replace(/Service$/, '')}_${m.name}(input: Uint8Array = new Uint8Array(0)): Promise<Uint8Array> {`,
    `    return this.transport.调用(${s.id}, ${m.id}, input);`, '  }');
  out.push('}', ''); return out.join('\n');
}
export function outputs(schema) {
  validatePrivateRpc(schema);
  const aliases = JSON.parse(read('tools/rpc-index-methods.json')), baseline = dispatchBaseline(schema);
  const header = read('native/rsharmony/include/rsharmony.h');
  return new Map([
    ['entry/src/main/ets/proto/generated/CoreMessages.ts', renderMessages(schema)],
    ['entry/src/main/ets/proto/generated/CoreRpc.ts', renderClient(schema)],
    ['entry/src/main/ets/proto/generated/PrivateRpc.ts', renderPrivateRpc()],
    ['native/rsharmony/src/protocol_generated.rs', renderRustMessages(schema)],
    ['native/rsharmony/src/custom_scheduling_schema.rs', renderSchedulingSchema(schema)],
    ['native/rsharmony/src/private_rpc_ids.rs', renderPrivateNativeIds()],
    ['tools/protocol/inventory.json', JSON.stringify(inventory(schema),null,2)+'\n'],
    ['tools/rpc-index-baseline.json', JSON.stringify(baseline, null, 2) + '\n'],
    ['entry/src/main/ets/backend/服务索引.ts', renderRpcIndex(aliases, baseline, header)],
    ['native/rsharmony/src/rpc_ids.rs', renderNativeRpcIds(baseline)],
    ['native/napi_bridge/src/rpc_ids.h', renderNativeRpcIds(baseline, true)]
  ]);
}
export function validatePrivateRpc(schema) {
  const spec=JSON.parse(read('tools/protocol/private-rpc.json'));
  const ids=new Set(schema.services.map(service=>service.id));
  const messages=new Set(schema.messages.map(message=>message.name));
  for(const[name,service]of Object.entries(spec)) {
    if(!Number.isInteger(service.id)||ids.has(service.id)) throw Error('Conflicting private service: '+name);
    ids.add(service.id);
    if(Object.keys(service.contracts??{}).join() !== Object.keys(service.methods).join()) throw Error('Missing private method contracts: '+name);
    if(new Set(Object.values(service.methods)).size !== Object.keys(service.methods).length) throw Error('Conflicting private methods: '+name);
    for(const method of Object.keys(service.methods)) for(const side of ['input','output']) if(!messages.has(service.contracts[method][side])) throw Error('Unknown private RPC '+side+': '+name+'.'+method);
  }
}
export function renderPrivateRpc() {
  const spec=JSON.parse(read('tools/protocol/private-rpc.json'));
  return '// SPDX-License-Identifier: AGPL-3.0-or-later\n// Generated by tools/core-protocol.mjs; do not edit.\n'+"import type { CoreTransport } from './CoreRpc';\n"+Object.entries(spec).map(([name,s])=>`export class ${name}Rpc {\n  static readonly SERVICE: number = ${s.id};\n  private transport: CoreTransport;\n  constructor(transport: CoreTransport) { this.transport = transport; }\n${Object.entries(s.methods).map(([m,id])=>`  ${m}(input: Uint8Array = new Uint8Array(0)): Promise<Uint8Array> { return this.transport.调用(${s.id}, ${id}, input); }`).join('\n')}\n}`).join('\n')+'\n';
}
export function renderPrivateNativeIds() {
  const spec=JSON.parse(read('tools/protocol/private-rpc.json'));
  const constant=n=>n.replace(/([a-z])([A-Z])/g,'$1_$2').toUpperCase();
  return '// SPDX-License-Identifier: AGPL-3.0-or-later\n// Generated by tools/core-protocol.mjs; do not edit.\n' + Object.entries(spec).flatMap(([n,s])=>[
    `#[allow(dead_code)]\npub const ${constant(n)}: u32 = ${s.id};`,
    ...Object.entries(s.methods).map(([method,id])=>`#[allow(dead_code)]\npub const ${constant(n)}_${constant(method)}: u32 = ${id};`)
  ]).join('\n')+'\n';
}
export function renderRustMessages(schema) {
  const messages=new Map(schema.messages.map(m=>[m.name,m]));
  const needed=new Set(JSON.parse(read('tools/protocol/native-messages.json')));
  for(const n of needed) for(const f of messages.get(n).fields) if(f.kind==='message') needed.add(f.target);
  const out=['// SPDX-License-Identifier: AGPL-3.0-or-later','// Generated by tools/core-protocol.mjs; do not edit.'];
  for(const n of needed){const m=messages.get(n);out.push('#[allow(dead_code)]','#[derive(Clone, PartialEq, prost::Message)]',`pub struct ${className(n)} {`);
    for(const f of m.fields){if(f.oneof)throw Error('Native projection requires explicit oneof policy: '+n);
      const types={int32:'i32',sint32:'i32',sfixed32:'i32',uint32:'u32',fixed32:'u32',int64:'i64',sint64:'i64',sfixed64:'i64',uint64:'u64',fixed64:'u64',float:'f32',double:'f64',bool:'bool',string:'String',bytes:'Vec<u8>',enum:'i32',message:className(f.target??'unused')};
      const optional=f.optional||f.kind==='message'&&!f.list&&!f.map;
      const repeated=f.list||f.map;
      const ty=types[f.kind];
      out.push(`    #[prost(${f.kind==='enum'?'int32':f.kind==='bytes'?'bytes = "vec"':f.kind}${repeated?', repeated':''}${optional?', optional':''}${repeated&&!['message','string','bytes'].includes(f.kind)?`, packed = "${f.packed}"`:''}, tag = "${f.id}")]`,
        `    pub ${f.name}: ${repeated?'Vec<'+ty+'>':optional?'Option<'+ty+'>':ty},`);
    }out.push('}','');
  }
  return out.join('\n');
}
export function renderSchedulingSchema(schema) {
  const nodes=JSON.parse(read('tools/protocol/scheduling-nodes.json'));
  const messages=new Map(schema.messages.map(m=>[m.name,m]));
  const out=['// SPDX-License-Identifier: AGPL-3.0-or-later','// Generated by tools/core-protocol.mjs; do not edit.','#[rustfmt::skip]','fn schema(node: &str) -> Vec<Field> {','    match node {'];
  for(const[node,name]of Object.entries(nodes)){out.push(`        "${node}" => vec![`);for(const f of messages.get(name).fields){
    let kind={uint32:'Kind::Uint',uint64:'Kind::Seed',float:'Kind::Float',bool:'Kind::Bool',string:'Kind::Text'}[f.kind];
    if(f.kind==='message'){const target=Object.entries(nodes).find(([,n])=>n===f.target)?.[0];if(!target)throw Error('Unknown scheduling node '+f.target);kind=`Kind::Node("${target}")`;}
    if(!kind||f.list||f.map)throw Error('Unsupported scheduling field '+name+'.'+f.name);
    const optional=!!(f.oneof||f.optional||f.jsonName==='memoryState');
    out.push(`            Field { id: ${f.id}, name: "${f.jsonName}", kind: ${kind}, optional: ${optional} },`);
  }out.push('        ],');}out.push('        _ => unreachable!(),','    }','}','');return out.join('\n');
}
export function checkGenerated(schema, check = true) {
  if (schema.revision !== lock().ANKI_RELEASE_COMMIT) throw new Error('Protocol schema differs from UPSTREAM.lock');
  if (existsSync(path.join(root,'third_party/anki/proto'))) {
    if (protocolFingerprint(path.join(root,'third_party/anki')) !== schema.fingerprint) throw new Error('Protocol/generator archive differs from official locked inputs');
  }
  if (createHash('sha256').update(readFileSync(path.join(root,'tools/protocol/core-descriptors.bin'))).digest('hex') !== schema.descriptorSha256) throw new Error('Descriptor snapshot differs from official export');
  if (schema.privateFingerprint !== privateFingerprint()) throw new Error('Private protocol schema is stale; refresh descriptors');
  for (const [file, source] of outputs(schema)) {
    if (check) { if (read(file).replace(/\r\n/g, '\n') !== source) throw new Error(`Stale generated protocol: ${file}`); }
    else { mkdirSync(path.dirname(path.join(root, file)), {recursive:true}); writeFileSync(path.join(root, file), source); }
  }
}
export function diffSchemas(before, after) {
  const changes = [];
  for (const key of ['services', 'messages', 'enums']) {
    const a = new Map(before[key].map(x => [x.name, x])), b = new Map(after[key].map(x => [x.name, x]));
    for (const name of new Set([...a.keys(), ...b.keys()])) if (JSON.stringify(a.get(name)) !== JSON.stringify(b.get(name)))
      changes.push({kind:key, name, before:a.get(name) ?? null, after:b.get(name) ?? null});
  }
  return changes;
}
export function parseArguments(args) {
  const [mode = '--check', source, extra] = args;
  const valid = (['--check','--generate'].includes(mode) && args.length <= 1) ||
    (mode === '--refresh' && args.length === 2 && !!source) ||
    (mode === '--diff' && args.length === 3 && !!source && !!extra);
  if (!valid) throw new Error('Usage: core-protocol.mjs --check|--generate|--refresh <official checkout>|--diff <before.json> <after.json>');
  return {mode, source, extra};
}
export function verifyOfficialCheckout(anki, revision, repository) {
  verifyGenerationCheckout(anki, revision);
  const origin = execFileSync('git',['-C',anki,'remote','get-url','origin'],{encoding:'utf8'}).trim();
  if (origin.replace(/\.git$/,'') !== repository.replace(/\.git$/,'')) throw new Error('Expected official Anki origin');
  if (execFileSync('git',['-C',anki,'status','--porcelain','--untracked-files=all'],{encoding:'utf8'}).trim()) throw new Error('Official checkout must be completely clean');
  return origin;
}
async function main() {
  const {mode, source, extra} = parseArguments(process.argv.slice(2));
  if (mode === '--diff') { console.log(JSON.stringify(diffSchemas(JSON.parse(readFileSync(source)), JSON.parse(readFileSync(extra))),null,2)); return; }
  if (mode === '--refresh') {
    const locked = lock();
    const anki = path.resolve(source);
    const origin = verifyOfficialCheckout(anki, locked.ANKI_RELEASE_COMMIT, locked.ANKI_REPOSITORY);
    const fingerprint = protocolFingerprint(anki);
    const privateHash = privateFingerprint();
    if (protocolFingerprint(path.join(root,'third_party/anki')) !== fingerprint) throw new Error('Exporter helper checkout differs from official inputs');
    const tmp = mkdtempSync(path.join(tmpdir(),'jide-protocol-'));
    const bin = path.join(tmp,'descriptors.bin'), json = path.join(tmp,'schema.json');
    execFileSync(process.env.PROTOC ?? 'protoc', [`--proto_path=${path.join(anki,'proto')}`, '--include_imports','--include_source_info', `--descriptor_set_out=${bin}`,
      `--proto_path=${path.join(root,'tools/protocol')}`,
      ...readdirSync(path.join(anki,'proto/anki')).filter(f=>f.endsWith('.proto')).sort().map(f=>path.join(anki,'proto/anki',f)),path.join(root,'tools/protocol/private.proto')],{stdio:'inherit'});
    execFileSync('cargo',['run','--locked','--manifest-path','tools/protocol-export/Cargo.toml','--',bin,json],{cwd:root,stdio:'inherit'});
    // 输入在外部进程运行期间发生变化时拒绝收录。
    if (verifyOfficialCheckout(anki, locked.ANKI_RELEASE_COMMIT, locked.ANKI_REPOSITORY) !== origin) throw new Error('Official origin changed during export');
    if (protocolFingerprint(anki) !== fingerprint) throw new Error('Protocol inputs changed during export');
    if (protocolFingerprint(path.join(root,'third_party/anki')) !== fingerprint || privateFingerprint() !== privateHash || JSON.stringify(lock()) !== JSON.stringify(locked)) throw new Error('Local protocol inputs changed during export');
    const schema = {revision:locked.ANKI_RELEASE_COMMIT, fingerprint,
      officialCommit:execFileSync('git',['-C',anki,'rev-parse','HEAD'],{encoding:'utf8'}).trim(),
      officialOrigin:origin, protocVersion:execFileSync(process.env.PROTOC ?? 'protoc',['--version'],{encoding:'utf8'}).trim(),
      descriptorSha256:createHash('sha256').update(readFileSync(bin)).digest('hex'),
      privateFingerprint:privateHash, ...JSON.parse(readFileSync(json))};
    // Reject unsupported mappings before replacing the reviewed descriptor/schema snapshot.
    outputs(schema);
    copyFileSync(bin,path.join(root,'tools/protocol/core-descriptors.bin'));
    writeFileSync(path.join(root,'tools/core-protocol-schema.json'),JSON.stringify(schema,null,2)+'\n');
    checkGenerated(schema,false);
  } else {
    const schema=JSON.parse(read('tools/core-protocol-schema.json'));
    verifyDescriptors(schema);
    checkGenerated(schema, mode === '--check');
  }
  console.log('[core-protocol] complete descriptor, official dispatch and static ArkTS outputs checked');
}
export function verifyDescriptors(schema) {
  const tmp=mkdtempSync(path.join(tmpdir(),'jide-descriptor-check-'));
  const json=path.join(tmp,'schema.json');
  if (protocolFingerprint(path.join(root,'third_party/anki')) !== schema.fingerprint) throw new Error('Exporter helper differs from official source');
  execFileSync('cargo',['run','--locked','--manifest-path','tools/protocol-export/Cargo.toml','--',path.join(root,'tools/protocol/core-descriptors.bin'),json],{cwd:root,stdio:'inherit'});
  const exported=JSON.parse(readFileSync(json));
  if (protocolFingerprint(path.join(root,'third_party/anki')) !== schema.fingerprint) throw new Error('Exporter inputs changed during check');
  for(const key of Object.keys(exported)) if(JSON.stringify(exported[key]) !== JSON.stringify(schema[key])) throw new Error('Schema is not derived from official descriptor snapshot: '+key);
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try { await main(); } catch(e) { console.error(e.message); process.exitCode=1; }
}
