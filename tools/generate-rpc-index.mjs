import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';
import { serviceNames, methodNames } from './verify-rpc-index.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
export function renderNativeRpcIds(baseline, cpp = false) {
  const method = (service, name) => {
    const matches = Object.entries(baseline.services[service].methods).filter(([, value]) => value === name);
    if (matches.length !== 1) throw new Error(`Missing native method ${service}.${name}`);
    return Number(matches[0][0]);
  };
  const ids = { SYNC_SERVICE: baseline.services.sync.id, ABORT_SYNC: method('sync', 'abort_sync'),
    COLLECTION_SERVICE: baseline.services.collection.id, OPEN_COLLECTION: method('collection', 'open_collection'),
    CLOSE_COLLECTION: method('collection', 'close_collection'), MEDIA_SERVICE: baseline.services.media.id,
    CHECK_MEDIA: method('media', 'check_media'), TRASH_MEDIA_FILES: method('media', 'trash_media_files') };
  return '// SPDX-License-Identifier: AGPL-3.0-or-later\n// Generated by tools/generate-rpc-index.mjs; do not edit.\n' +
    (cpp ? '#pragma once\n#include <cstdint>\n' : '') +
    Object.entries(ids).map(([name, id]) => cpp ? `constexpr uint32_t RPC_${name} = ${id};` : `pub const ${name}: u32 = ${id};`).join('\n') + '\n';
}

export function writeGeneratedIndexes(manifest, baseline, header) {
  const outputs = [
    ['entry/src/main/ets/backend/服务索引.ts', renderRpcIndex(manifest, baseline, header)],
    ['native/rsharmony/src/rpc_ids.rs', renderNativeRpcIds(baseline)],
    ['native/napi_bridge/src/rpc_ids.h', renderNativeRpcIds(baseline, true)]
  ];
  for (const [target, output] of outputs) writeFileSync(path.join(root, target), output);
}
export function renderRpcIndex(manifest, baseline, header) {
  const lines = ['// SPDX-License-Identifier: AGPL-3.0-or-later',
    '// Generated by node tools/generate-rpc-index.mjs; do not edit numeric IDs.',
    '// Sources: locked backend.rs baseline + rpc-index-methods.json + rsharmony.h.', ''];
  const table = (name, entries) => {
    lines.push(`export const ${name} = {`, entries.map(([key, value]) => `  ${key}: ${value}`).join(',\n'), '} as const;', '');
  };
  table('服务号', [...serviceNames].map(([alias, service]) => {
    const id = baseline.services[service]?.id;
    if (!Number.isInteger(id)) throw new Error(`Missing service ${service}`);
    return [alias, id];
  }));
  for (const [tableName, service] of methodNames) {
    if (!manifest.methods[tableName]) throw new Error(`Missing aliases ${tableName}`);
    table(tableName, Object.entries(manifest.methods[tableName]).map(([alias, method]) => {
      const matches = Object.entries(baseline.services[service].methods).filter(([, name]) => name === method);
      if (matches.length !== 1) throw new Error(`Ambiguous/missing method ${service}.${method}`);
      return [alias, Number(matches[0][0])];
    }));
  }
  if (Object.keys(manifest.methods).length !== methodNames.size) throw new Error('Unmapped method table');
  const statuses = [...header.matchAll(/ANKI_STATUS_([A-Z_]+)\s*=\s*(\d+)/g)];
  const aliases = { OK: '成功', INVALID_ARGUMENT: '参数非法', HANDLE_NOT_FOUND: '句柄未找到', BACKEND_ERROR: '后端错误', NATIVE_FATAL: '原生致命错误' };
  if (statuses.length !== Object.keys(aliases).length || statuses.some(m => !aliases[m[1]])) throw new Error('Unmapped native status');
  table('原生状态', statuses.map(m => [aliases[m[1]], Number(m[2])]));
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    if (process.argv.length > 3 || (process.argv[2] && process.argv[2] !== '--check')) throw new Error('Usage: node tools/generate-rpc-index.mjs [--check]');
    const read = name => readFileSync(path.join(root, name), 'utf8');
    const manifest = JSON.parse(read('tools/rpc-index-methods.json'));
    const baseline = JSON.parse(read('tools/rpc-index-baseline.json'));
    const lock = Object.fromEntries(read('UPSTREAM.lock').trim().split(/\r?\n/).map(line => line.split('=')));
    if (baseline.revision !== lock.ANKI_RELEASE_COMMIT || manifest.ankiRevision !== `${lock.ANKI_TAG}-${baseline.revision}`) throw new Error('RPC inputs do not match UPSTREAM.lock');
    const header = read('native/rsharmony/include/rsharmony.h');
    if (process.argv[2] === '--check') {
      for (const [target, output] of [
        ['entry/src/main/ets/backend/服务索引.ts', renderRpcIndex(manifest, baseline, header)],
        ['native/rsharmony/src/rpc_ids.rs', renderNativeRpcIds(baseline)],
        ['native/napi_bridge/src/rpc_ids.h', renderNativeRpcIds(baseline, true)]
      ]) if (read(target).replace(/\r\n/g, '\n') !== output) throw new Error(`Generated RPC index is stale: ${target}; run node tools/generate-rpc-index.mjs`);
    } else writeGeneratedIndexes(manifest, baseline, header);
    console.log('[rpc-index] generated source matches locked dispatch');
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
